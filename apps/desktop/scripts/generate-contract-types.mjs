#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

import { compile } from 'json-schema-to-typescript';

const projectDir = path.resolve(import.meta.dirname, '..');
const repoRoot = path.resolve(projectDir, '..', '..');
const options = parseArgs(process.argv.slice(2));
const schemaPath = options.schema ?? path.join(repoRoot, 'contracts', 'rpc.schema.json');
const outputPath = options.output ?? path.join(repoRoot, 'contracts', 'generated.ts');

const bannerComment = [
  '/*',
  ' * Generated from contracts/rpc.schema.json by json-schema-to-typescript.',
  ' * Do not edit this file by hand.',
  ' */',
].join('\n');

async function main() {
  const schemaText = await readFile(schemaPath, 'utf8').catch(() => {
    throw new Error(`contract schema not found: ${schemaPath}`);
  });
  const schema = JSON.parse(schemaText);
  const generated = await compile(schema, 'WorkbenchRpcContract', {
    bannerComment,
    additionalProperties: false,
    style: { singleQuote: true },
  });
  const normalized = `${generated.trimEnd()}\n`;

  if (options.check) {
    const existing = await readFile(outputPath, 'utf8').catch(() => '');
    if (existing !== normalized) {
      console.error(`contract types drifted: ${outputPath}`);
      process.exitCode = 1;
      return;
    }
    console.log(`contract types match: ${path.relative(repoRoot, outputPath)}`);
    return;
  }

  await writeFile(outputPath, normalized, 'utf8');
  console.log(`contract types written: ${path.relative(repoRoot, outputPath)}`);
}

function parseArgs(argv) {
  const parsed = { check: false, schema: undefined, output: undefined };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--check') {
      parsed.check = true;
    } else if (arg === '--schema') {
      parsed.schema = path.resolve(argv[++index]);
    } else if (arg === '--output') {
      parsed.output = path.resolve(argv[++index]);
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }
  return parsed;
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
