"""Browser checks for the local, mock-only product review prototype."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import json

ROOT=Path(__file__).resolve().parent
OUT=ROOT/'output/playwright'
OUT.mkdir(parents=True,exist_ok=True)
URL='http://127.0.0.1:8765'
BROWSER='C:/Users/cb_lo/AppData/Local/ms-playwright/chromium-1208/chrome-win64/chrome.exe'
checks=[]

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=BROWSER)
    context=browser.new_context(viewport={'width':1440,'height':1000},reduced_motion='reduce')
    page=context.new_page()
    errors=[]
    requests=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:requests.append(r.url))
    page.goto(URL,wait_until='networkidle')
    page.screenshot(path=str(OUT/'01-workbench.png'),full_page=True)
    expect(page.locator('h1')).to_contain_text('知序，和你一起完成')
    checks.append('Home renders shared navigation and central office/development/design modules')

    page.locator('[data-action="new-build"]').first.click()
    expect(page.locator('.stepper')).to_contain_text('10 道')
    page.screenshot(path=str(OUT/'02-question-setup.png'),full_page=True)
    page.locator('[data-action="run-build"]:visible').click()
    page.locator('[data-action="cancel-build"]').click()
    expect(page.get_by_role('heading',name='整理已暂停。')).to_be_visible()
    page.wait_for_timeout(3300)
    expect(page.locator('[data-action="save-candidates"]')).to_have_count(0)
    checks.append('Cancelling demo generation prevents delayed results')
    page.locator('[data-action="run-build"]:visible').click()
    page.locator('[data-action="save-candidates"]').wait_for(state='visible')
    expect(page.locator('[data-action="toggle-candidate"]')).to_have_count(10)
    page.screenshot(path=str(OUT/'03-generated-questions.png'),full_page=True)
    page.locator('[data-action="edit-question"]').first.click()
    page.locator('#edit-title').fill('工具调用中，模型和运行时如何分工？')
    page.locator('[data-action="save-question-edit"]').click()
    expect(page.locator('[data-action="candidate-detail"]').first).to_have_text('工具调用中，模型和运行时如何分工？')
    page.locator('[data-action="save-candidates"]').click()
    expect(page.locator('.stat strong').first).to_have_text('18')
    page.screenshot(path=str(OUT/'04-question-library.png'),full_page=True)
    checks.append('10 drafts can be edited and saved, producing 18 prototype questions')
    page.reload(wait_until='networkidle')
    page.locator('[data-page="bank"]').first.click()
    expect(page.locator('.stat strong').first).to_have_text('18')
    page.locator('#bank-search').fill('工具调用中，模型')
    expect(page.locator('tbody tr')).to_have_count(1)
    checks.append('Saved prototype questions persist after reload and are searchable')

    page.locator('[data-page="more"]').first.click()
    page.locator('[data-page="interview"]').first.click()
    page.screenshot(path=str(OUT/'05-interview-setup.png'),full_page=True)
    page.locator('[data-action="start-interview"]').click()
    page.locator('[data-action="submit-answer"]').click()
    expect(page.locator('.question-eyebrow')).to_contain_text('主问题')
    page.locator('#answer').fill('模型返回工具名称与参数，运行时校验后执行 Python 函数，再返回工具结果。')
    page.locator('[data-action="hint"]').click()
    expect(page.locator('.hint-status')).to_contain_text('使用过提示')
    expect(page.locator('#answer')).to_have_value('模型返回工具名称与参数，运行时校验后执行 Python 函数，再返回工具结果。')
    page.screenshot(path=str(OUT/'06-text-interview.png'),full_page=True)
    page.locator('[data-action="submit-answer"]').click()
    expect(page.locator('.question-eyebrow')).to_contain_text('FOLLOW-UP')
    page.locator('[data-action="live-input"][data-value="voice"]').click()
    page.locator('[data-action="start-voice"]').click()
    expect(page.locator('#voice-time')).to_be_visible()
    expect(page.locator('[data-action="submit-answer"]')).to_be_disabled()
    page.screenshot(path=str(OUT/'07-voice-recording.png'),full_page=True)
    page.locator('[data-action="stop-voice"]').click()
    expect(page.locator('#answer')).to_contain_text('演示转写')
    page.locator('#answer').fill('为了避免超时后重复执行，需要给操作设置幂等标识并保留执行状态。')
    page.screenshot(path=str(OUT/'08-voice-transcript.png'),full_page=True)
    page.locator('[data-action="submit-answer"]').click()
    checks.append('Text answer, hint state, follow-up and editable demo voice transcript work')
    page.locator('[data-action="finish-interview"]').click()
    expect(page.get_by_role('heading',name='把这次的卡点，变成下次的进步。')).to_be_visible()
    expect(page.locator('.report-block')).to_have_count(4)
    page.locator('[data-action="report-review"]').click()
    page.screenshot(path=str(OUT/'09-interview-report.png'),full_page=True)
    page.locator('[data-page="review"]').first.click()
    expect(page.locator('.review-card')).to_have_count(1)
    checks.append('Report preserves answer records and creates linked review item')

    page.get_by_role('button',name='设置',exact=True).click()
    page.locator('#default-batch').fill('8')
    page.locator('[data-action="save-defaults"]').click()
    page.screenshot(path=str(OUT/'10-default-settings.png'),full_page=True)
    page.locator('[data-page="bank"]').first.click()
    page.locator('[data-action="new-build"]').click()
    expect(page.locator('.stepper')).to_contain_text('8 道')
    checks.append('Default settings affect subsequent tasks')
    page.locator('[data-page="agents"]').first.click()
    page.locator('[data-action="new-agent"]').click()
    page.locator('#agent-name').fill('Java 项目追问助手')
    page.locator('#agent-prompt').fill('结合真实项目经历，练习工程取舍与故障定位。')
    page.locator('[data-action="save-agent"]').click()
    expect(page.get_by_role('heading',name='Java 项目追问助手')).to_be_visible()
    page.screenshot(path=str(OUT/'11-agent-center.png'),full_page=True)
    checks.append('Custom Agent demo configuration can be created locally')

    for width in [1024,768,390]:
        page.set_viewport_size({'width':width,'height':900})
        page.locator('[data-page="home"]').first.click()
        assert page.evaluate('document.documentElement.scrollWidth')<=width
        page.screenshot(path=str(OUT/f'home-{width}.png'),full_page=True)
        page.locator('[data-action="new-build"]').first.click()
        visible=page.locator('[data-action="run-build"]:visible').count()
        checks.append(f'{width}px builder primary action visibility: {visible}')
        assert visible>0, f'Builder primary action missing at {width}px'
    page.set_viewport_size({'width':1440,'height':1000})
    page.locator('[data-page="more"]').first.click()
    page.locator('[data-page="interview"]').first.click()
    page.locator('[data-action="interview-mode"][data-value="training"]').click()
    page.locator('[data-action="start-interview"]').click()
    for expected in [1,2]:
        page.locator('[data-action="sample-answer"]').click()
        page.locator('[data-action="submit-answer"]').click()
        expect(page.locator('.live-top')).to_contain_text('追问 '+str(expected)+' / 2')
    page.locator('[data-action="sample-answer"]').click()
    page.locator('[data-action="submit-answer"]').click()
    expect(page.locator('[data-action="next-question"]')).to_be_visible()
    expect(page.locator('.feedback')).to_be_visible()
    page.locator('[data-action="next-question"]').click()
    expect(page.locator('.live-top')).to_contain_text('第 2 / 5 题')
    page.reload(wait_until='networkidle')
    page.locator('[data-action="resume"]').first.click()
    expect(page.locator('.live-top')).to_contain_text('第 2 / 5 题')
    checks.append('Two follow-ups lead to per-question feedback; reloaded session resumes at saved question')
    page.locator('[data-action="finish-interview"]').click()
    page.locator('[data-action="setup-interview"]').click()
    page.locator('[data-action="interview-mode"][data-value="mock"]').click()
    page.locator('[data-action="start-interview"]').click()
    page.locator('[data-action="dont-know"]').click()
    expect(page.locator('.live-top')).to_contain_text('第 2 / 5 题')
    expect(page.locator('.feedback')).to_have_count(0)
    page.locator('[data-action="finish-interview"]').click()
    expect(page.locator('.report-block')).to_have_count(3)
    checks.append('Mock interview withholds feedback until the report and preserves unknown answers')
    assert not errors,errors
    assert all(url.startswith(URL) or url.startswith('blob:') for url in requests),requests
    result={'passed':True,'checks':checks,'page_errors':errors,'external_requests':[]}
    (OUT/'verification.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(result,ensure_ascii=False,indent=2))
    browser.close()
